#!/usr/bin/env bash
# Tests for the knowledge board script shipped in the template:
#   - template/.claude/scripts/knowledge-board.sh
#
#   tests/test-knowledge-board.sh
#   FAKE_JQ=gojq tests/test-knowledge-board.sh   # apply --jq with gojq, the jq built into gh
#
# A fake `gh` serves fixture JSON per REST endpoint, applies `--jq` with the real jq (or $FAKE_JQ),
# and stores the body sent by `-X PATCH ... -F body=@<file>`, so the script runs without network.
# Requires: bash, git, jq.

set -uo pipefail

ROOT=$(cd "$(dirname "$0")/.." && pwd)
SCRIPT="$ROOT/template/.claude/scripts/knowledge-board.sh"

pass=0
fail=0
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

ok()  { pass=$((pass + 1)); printf 'PASS  %s\n' "$1"; }
bad() { fail=$((fail + 1)); printf 'FAIL  %s\n%s\n' "$1" "${2:-}"; }
has() { [[ "$out" == *"$2"* ]] && ok "$1" || bad "$1 (missing: $2)" "$out"; }
hasnt() { [[ "$out" != *"$2"* ]] && ok "$1" || bad "$1 (unexpected: $2)" "$out"; }

FOOTER=$'---\n_Generated by [Claude Code](https://claude.ai/code)_'

# --- fake gh ---------------------------------------------------------------
# gh api [-X METHOD] <endpoint> [--jq <expr>] [-F body=@<file> | -F body=@-]: serves
# $FX/<endpoint with / ? & = replaced by _>.json and logs "METHOD endpoint" to $FX/calls.log.
# PATCH stores the file's content as .body. FAKE_FOOTER=1 does what the Claude Code cloud route
# does (moves the footer to the end, adding it when missing); FAKE_MANGLE=1 saves something else.
mkdir -p "$TMP/bin"
cat >"$TMP/bin/gh" <<'EOF'
#!/usr/bin/env bash
[[ "${1:-}" == api ]] || { echo "fake gh: only 'api' is supported" >&2; exit 1; }
shift
method=GET ep="" jqx="" field=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    -X) method="$2"; shift 2 ;;
    --jq) jqx="$2"; shift 2 ;;
    -F|-f) field="$2"; shift 2 ;;
    -*) shift ;;
    *) ep="$1"; shift ;;
  esac
done
ep=${ep//"{owner}/{repo}"/o/r}
printf '%s %s\n' "$method" "$ep" >>"$FX/calls.log"
f="$FX/$(printf '%s' "$ep" | tr '/?&=' '____').json"
[[ -f "$f" ]] || { echo "gh: Not Found (HTTP 404)" >&2; exit 1; }
if [[ "$method" == PATCH ]]; then
  src=${field#body=@}
  if [[ "$src" == - ]]; then src="$FX/stdin.body"; cat >"$src"; fi
  if [[ "${FAKE_FOOTER:-}" == 1 ]]; then
    jq --rawfile b "$src" --arg F "$FOOTER" '.body = (($b | split("\n\n" + $F) | join("") | split($F) | join("") | sub("\n+$"; "")) + "\n\n" + $F)' "$f" >"$f.tmp"
  elif [[ "${FAKE_MANGLE:-}" == 1 ]]; then
    jq --rawfile b "$src" '.body = ($b + "\nsomething else")' "$f" >"$f.tmp"
  else
    jq --rawfile b "$src" '.body = $b' "$f" >"$f.tmp"
  fi
  mv "$f.tmp" "$f"
  cat "$f"
  exit 0
fi
if [[ -n "$jqx" ]]; then "${FAKE_JQ:-jq}" -r "$jqx" "$f"; else cat "$f"; fi
EOF
chmod +x "$TMP/bin/gh"

# fx <dir> <endpoint> <json>: write one fixture
fx() { printf '%s\n' "$3" >"$1/$(printf '%s' "$2" | tr '/?&=' '____').json"; }
# comment <id> <body>: one comment object
comment() {
  jq -cn --argjson id "$1" --arg b "$2" '{id: $id, body: $b, created_at: "2026-10-0\($id % 9 + 1)T00:00:00Z",
    html_url: "https://github.com/o/r/issues/7#issuecomment-\($id)", user: {login: "someone"}}'
}

# project <dir> <board line>: a git repository holding the script and workflow-feedback.md
project() {
  mkdir -p "$1/.claude/scripts" "$1/.claude/rules" "$1/fx"
  cp "$SCRIPT" "$1/.claude/scripts/"
  printf '# ワークフロー改善の知見ボード\n\n## 知見ボードIssue\n\n%s\n- **タイトル**: `meta: ワークフロー改善の知見ボード`\n' "$2" \
    >"$1/.claude/rules/workflow-feedback.md"
  git init -q "$1"
}

# run <project dir> <args...>: run the script with the fake gh; sets out / rc
run() {
  local dir="$1"; shift
  : >"$dir/fx/calls.log"
  out=$(cd "$dir" && FX="$dir/fx" FOOTER="$FOOTER" PATH="$TMP/bin:$PATH" bash .claude/scripts/knowledge-board.sh "$@" 2>&1)
  rc=$?
}
calls() { cat "$1/fx/calls.log"; }

