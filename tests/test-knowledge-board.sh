[[ "$(jq -r .body "$P/fx/repos_o_r_issues_comments_108.json")" == *$'✅ Issue u/t#7 で対応\n\n'"$FOOTER" ]] && ok "the fake moved the footer below the marker" || bad "fake footer" "$(jq -r .body "$P/fx/repos_o_r_issues_comments_108.json")"

out=$(cd "$P" && : >fx/calls.log && FX="$P/fx" FOOTER="$FOOTER" FAKE_MANGLE=1 PATH="$TMP/bin:$PATH" bash .claude/scripts/knowledge-board.sh mark 104 '✅ Issue #32' 2>&1); rc=$?
